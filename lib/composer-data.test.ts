import test from "node:test";
import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { composerDataChanged, publishInfoData, readInfoData, publishDiffData, readDiffData, clearComposerData } from "./composer-data.ts";

test("SDK data stays typed, notifies only on changes and belongs to one composer", () => {
  const dom = new JSDOM('<div id="one"></div><div id="two"></div>');
  const one = dom.window.document.getElementById('one')!;
  const two = dom.window.document.getElementById('two')!;
  let changes=0;
  dom.window.document.addEventListener(composerDataChanged, () => changes++);
  const data={ settings:{showChildren:'상단 표시'}, children:[{id:'child',title:'첫 번째',providerId:'codex',state:'run' as const}], parent:null };
  publishInfoData(one,data);
  assert.equal(readInfoData(one)?.value,data,'consumer reads the SDK object without serializing it');
  assert.equal(one.attributes.length,1,'no JSON attributes are written');
  assert.equal(changes,1);
  const revision=readInfoData(one)?.revision;
  publishInfoData(one,structuredClone(data));
  assert.equal(changes,1,'equal SDK refresh does not notify or replace the snapshot');
  assert.equal(readInfoData(one)?.value,data);
  assert.equal(readInfoData(two),undefined);
  const openThread=(_id:string)=>{};
  publishInfoData(one,{...data,openThread});
  assert.equal(readInfoData(one)?.revision,revision,'a new action closure is not a visual update');
  assert.equal(readInfoData(one)?.value.openThread,openThread);
  assert.equal(changes,1);
  publishInfoData(one,{...data,children:[{...data.children[0],title:'다음 제목'}]});
  assert.equal(changes,2);
  assert.notEqual(readInfoData(one)?.revision,revision);
  assert.equal(readInfoData(one)?.value.children[0].title,'다음 제목');
  const childRevision=readInfoData(one)?.childrenRevision;
  publishInfoData(one,{...readInfoData(one)!.value,parent:{id:'parent',title:'부모',providerId:'codex'}});
  assert.equal(readInfoData(one)?.childrenRevision,childRevision,'a parent update is not a child-avatar change');
  clearComposerData(one);
  assert.equal(readInfoData(one),undefined);
  assert.equal(changes,4);
  clearComposerData(one);assert.equal(changes,4);
  dom.window.close();
});

test("Diff data preserves loading, empty, branch changes and isolated lifetimes", () => {
  const dom=new JSDOM('<span></span><span></span>');
  const [one,two]=dom.window.document.querySelectorAll('span');
  const snapshot={insertions:2,deletions:1,files:1,branch:'feature/ui'};
  publishDiffData(one,{threadId:'first',state:'loading',summary:null});
  publishDiffData(two,{threadId:'second',state:'ready',summary:snapshot});
  assert.equal(readDiffData(one)?.value.state,'loading');
  assert.equal(readDiffData(two)?.value.summary,snapshot);
  publishDiffData(one,{threadId:'first',state:'ready',summary:snapshot});
  const before=readDiffData(one)?.revision;
  publishDiffData(one,{threadId:'first',state:'ready',summary:{...snapshot,branch:'main'}});
  assert.notEqual(readDiffData(one)?.revision,before);
  assert.equal(readDiffData(two)?.value.summary?.branch,'feature/ui');
  publishDiffData(one,{threadId:'next',state:'loading',summary:null});
  assert.equal(readDiffData(one)?.value.summary,null,'thread transition cannot retain the previous result');
  publishDiffData(one,{threadId:'next',state:'unavailable',summary:null});
  assert.equal(readDiffData(one)?.value.state,'unavailable');
  clearComposerData(one);assert.equal(readDiffData(one),undefined);
  assert.equal(readDiffData(two)?.value.summary,snapshot);
  dom.window.close();
});
